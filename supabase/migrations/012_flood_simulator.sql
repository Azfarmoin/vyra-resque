-- VYRA 012: Flood-Depth and Impact Simulator. Run AFTER 011_profiles_role_hardening.sql. Safe to run more than once.
--
-- DESIGN RULES
--   * Simulated data is stored ONLY in these tables. Nothing here has a foreign key to, or a trigger on, emergency_reports,
--     dispatches, report_events, rescue_teams or shelters. A scenario can never become an incident, change a priority or
--     dispatch anyone: the application code that reads real incidents is read-only, and these tables share no keys with them.
--   * Every scenario row is an ESTIMATE by construction: is_simulation is a column that must be TRUE (CHECK), so a row cannot
--     be saved claiming to be a real observation.
--   * Observations of real floods (flood_observations) are separate from scenarios. They are only ever entered by staff or
--     imported from a named source; the application never generates them.
--   * Row Level Security uses public.current_user_role(). Only responders and admins can read or write; citizens and
--     anonymous visitors see nothing.

CREATE OR REPLACE FUNCTION public.current_user_role()
RETURNS TEXT LANGUAGE sql STABLE SECURITY DEFINER SET search_path = public
AS $$ SELECT role::TEXT FROM public.profiles WHERE id = auth.uid() $$;

CREATE OR REPLACE FUNCTION public.update_updated_at_column()
RETURNS TRIGGER AS $$ BEGIN NEW.updated_at = NOW(); RETURN NEW; END; $$ LANGUAGE plpgsql;

-- Basic GeoJSON sanity check: Polygon / MultiPolygon with every coordinate inside the valid lon/lat range.
CREATE OR REPLACE FUNCTION public.flood_area_ok(g jsonb)
RETURNS boolean LANGUAGE sql IMMUTABLE
AS $$
  SELECT g IS NOT NULL
     AND g->>'type' IN ('Polygon', 'MultiPolygon')
     AND jsonb_typeof(g->'coordinates') = 'array'
     AND NOT jsonb_path_exists(g->'coordinates', '$.** ? (@.type() == "number" && (@ < -180 || @ > 180))')
$$;

-- ---------------------------------------------------------------------------------------------------------------
-- 1. Scenarios
-- ---------------------------------------------------------------------------------------------------------------
CREATE TABLE IF NOT EXISTS public.flood_scenarios (
  id              UUID PRIMARY KEY DEFAULT gen_random_uuid(),
  name            TEXT NOT NULL CHECK (char_length(btrim(name)) BETWEEN 3 AND 120),
  description     TEXT CHECK (description IS NULL OR char_length(description) <= 2000),
  -- hypothetical_overlay : a water level / depth typed in by a person, applied without terrain. NOT a hydraulic result.
  -- terrain_bathtub      : DEM-based "bathtub" estimate (water level vs ground height, optional connectivity). Screening only.
  -- terrain_rainfall     : DEM-based lowest-ground-first ponding from a rainfall volume. Screening only.
  -- imported_hydraulic   : output of an EXTERNAL hydraulic model, imported with its validation evidence by an administrator.
  scenario_kind   TEXT NOT NULL CHECK (scenario_kind IN ('hypothetical_overlay', 'terrain_bathtub', 'terrain_rainfall', 'imported_hydraulic')),
  is_simulation   BOOLEAN NOT NULL DEFAULT TRUE CHECK (is_simulation = TRUE),
  zone_label      TEXT,
  area            JSONB NOT NULL CHECK (public.flood_area_ok(area)),
  inputs          JSONB NOT NULL,          -- exactly what the user configured (validated)
  results         JSONB NOT NULL,          -- summary, band areas, asset exposure, data quality, assumptions, limitations
  layers          JSONB,                   -- map layers: depth bands as GeoJSON and (optionally) the packed depth grid
  model_version   TEXT,
  computed_at     TIMESTAMPTZ NOT NULL DEFAULT NOW(),
  created_by      UUID REFERENCES public.profiles(id) ON DELETE SET NULL,
  created_by_name TEXT,
  created_at      TIMESTAMPTZ NOT NULL DEFAULT NOW(),
  updated_at      TIMESTAMPTZ NOT NULL DEFAULT NOW()
);
CREATE INDEX IF NOT EXISTS idx_flood_scenarios_created ON public.flood_scenarios (created_at DESC);
CREATE INDEX IF NOT EXISTS idx_flood_scenarios_owner ON public.flood_scenarios (created_by, created_at DESC);

DROP TRIGGER IF EXISTS update_flood_scenarios_updated_at ON public.flood_scenarios;
CREATE TRIGGER update_flood_scenarios_updated_at BEFORE UPDATE ON public.flood_scenarios
  FOR EACH ROW EXECUTE FUNCTION public.update_updated_at_column();

-- ---------------------------------------------------------------------------------------------------------------
-- 2. Real flood observations (never generated by the application)
-- ---------------------------------------------------------------------------------------------------------------
CREATE TABLE IF NOT EXISTS public.flood_observations (
  id               UUID PRIMARY KEY DEFAULT gen_random_uuid(),
  lat              DOUBLE PRECISION NOT NULL CHECK (lat BETWEEN -90 AND 90),
  lng              DOUBLE PRECISION NOT NULL CHECK (lng BETWEEN -180 AND 180),
  depth_m          NUMERIC NOT NULL CHECK (depth_m >= 0 AND depth_m <= 20),
  observed_at      TIMESTAMPTZ NOT NULL CHECK (observed_at <= NOW() + INTERVAL '1 day'),
  source           TEXT NOT NULL CHECK (char_length(btrim(source)) BETWEEN 2 AND 200),   -- who measured it / which dataset
  source_url       TEXT CHECK (source_url IS NULL OR source_url ~* '^https?://'),
  method           TEXT CHECK (method IS NULL OR method IN ('gauge', 'field_measurement', 'photo_estimate', 'official_survey', 'other')),
  notes            TEXT CHECK (notes IS NULL OR char_length(notes) <= 1000),
  verified         BOOLEAN NOT NULL DEFAULT FALSE,
  recorded_by      UUID REFERENCES public.profiles(id) ON DELETE SET NULL,
  recorded_by_name TEXT,
  created_at       TIMESTAMPTZ NOT NULL DEFAULT NOW()
);
CREATE INDEX IF NOT EXISTS idx_flood_observations_geo ON public.flood_observations (lat, lng);
CREATE INDEX IF NOT EXISTS idx_flood_observations_time ON public.flood_observations (observed_at DESC);

-- ---------------------------------------------------------------------------------------------------------------
-- 3. Audit log (append-only: no UPDATE / DELETE policy)
-- ---------------------------------------------------------------------------------------------------------------
CREATE TABLE IF NOT EXISTS public.flood_audit_log (
  id          UUID PRIMARY KEY DEFAULT gen_random_uuid(),
  scenario_id UUID,                        -- deliberately no FK: history survives deleting a scenario
  action      TEXT NOT NULL CHECK (action IN ('simulate', 'create', 'update', 'delete', 'export', 'compare', 'import', 'observation')),
  actor_id    UUID,
  actor       TEXT NOT NULL,
  actor_role  TEXT,
  detail      JSONB,
  created_at  TIMESTAMPTZ NOT NULL DEFAULT NOW()
);
CREATE INDEX IF NOT EXISTS idx_flood_audit_scenario ON public.flood_audit_log (scenario_id, created_at DESC);

-- ---------------------------------------------------------------------------------------------------------------
-- 4. Row Level Security
-- ---------------------------------------------------------------------------------------------------------------
ALTER TABLE public.flood_scenarios    ENABLE ROW LEVEL SECURITY;
ALTER TABLE public.flood_observations ENABLE ROW LEVEL SECURITY;
ALTER TABLE public.flood_audit_log    ENABLE ROW LEVEL SECURITY;

DO $$
DECLARE p record;
BEGIN
  FOR p IN SELECT policyname, tablename FROM pg_policies
           WHERE schemaname = 'public' AND tablename IN ('flood_scenarios', 'flood_observations', 'flood_audit_log') LOOP
    EXECUTE format('DROP POLICY %I ON public.%I', p.policyname, p.tablename);
  END LOOP;
END $$;

-- Scenarios: staff read all (so a team can share them); staff create their own; owner or admin edits / deletes.
CREATE POLICY "flood scenarios: staff read" ON public.flood_scenarios FOR SELECT
  USING (public.current_user_role() IN ('responder', 'admin'));
CREATE POLICY "flood scenarios: staff create as themselves" ON public.flood_scenarios FOR INSERT
  WITH CHECK (public.current_user_role() IN ('responder', 'admin') AND created_by = auth.uid());
CREATE POLICY "flood scenarios: owner or admin update" ON public.flood_scenarios FOR UPDATE
  USING (public.current_user_role() IN ('responder', 'admin') AND (created_by = auth.uid() OR public.current_user_role() = 'admin'))
  WITH CHECK (public.current_user_role() IN ('responder', 'admin') AND (created_by = auth.uid() OR public.current_user_role() = 'admin'));
CREATE POLICY "flood scenarios: owner or admin delete" ON public.flood_scenarios FOR DELETE
  USING (public.current_user_role() IN ('responder', 'admin') AND (created_by = auth.uid() OR public.current_user_role() = 'admin'));

-- Observations: staff read; staff add their own unverified records; only an admin verifies; owner (if unverified) or admin deletes.
CREATE POLICY "flood observations: staff read" ON public.flood_observations FOR SELECT
  USING (public.current_user_role() IN ('responder', 'admin'));
CREATE POLICY "flood observations: staff add own unverified" ON public.flood_observations FOR INSERT
  WITH CHECK (public.current_user_role() IN ('responder', 'admin') AND recorded_by = auth.uid()
              AND (verified = FALSE OR public.current_user_role() = 'admin'));
CREATE POLICY "flood observations: admin update" ON public.flood_observations FOR UPDATE
  USING (public.current_user_role() = 'admin') WITH CHECK (public.current_user_role() = 'admin');
CREATE POLICY "flood observations: owner unverified or admin delete" ON public.flood_observations FOR DELETE
  USING (public.current_user_role() = 'admin' OR (recorded_by = auth.uid() AND verified = FALSE AND public.current_user_role() = 'responder'));

-- Audit: staff read; staff append rows naming themselves; nobody edits or deletes.
CREATE POLICY "flood audit: staff read" ON public.flood_audit_log FOR SELECT
  USING (public.current_user_role() IN ('responder', 'admin'));
CREATE POLICY "flood audit: staff append as themselves" ON public.flood_audit_log FOR INSERT
  WITH CHECK (public.current_user_role() IN ('responder', 'admin') AND actor_id = auth.uid());

