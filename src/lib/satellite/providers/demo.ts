// DEMONSTRATION provider. It generates a deterministic SYNTHETIC scene pair (a river that widens between the dates, a cloud,
// a cleared field) so the interface and workflow can be shown when no real imagery is available. It is never used unless
// demonstration mode is switched on, every scene is flagged synthetic, and results from it can never be confirmed.
import { FLAG, COLLECTION_KIND, type CollectionId, type SceneMeta } from '../types'
import type { LoadedScene } from '../analysis/engine'
import type { Grid } from '../raster/grid'
import { ProviderError, type ImageryProvider, type ProviderStatus, type SearchRequest, type SearchResult } from './types'

const rng = (seed: number) => () => { seed |= 0; seed = (seed + 0x6d2b79f5) | 0; let t = Math.imul(seed ^ (seed >>> 15), 1 | seed); t = (t + Math.imul(t ^ (t >>> 7), 61 | t)) ^ t; return ((t ^ (t >>> 14)) >>> 0) / 4294967296 }
const mid = (a: string, b: string) => new Date((Date.parse(`${a}T12:00:00Z`) + Date.parse(`${b}T12:00:00Z`)) / 2).toISOString().slice(0, 10)

export function demoEnabled(env: NodeJS.ProcessEnv = process.env, dataMode?: string) { return env.SATELLITE_DEMO_MODE === 'true' || dataMode === 'demo' }

function sceneFor(collection: CollectionId, day: string, bbox: SceneMeta['footprintBbox']): SceneMeta {
  const kind = COLLECTION_KIND[collection]
  return { id: `demo-${collection}-${day.replace(/-/g, '')}`, provider: 'demo', collection, kind, platform: 'SYNTHETIC-DEMO', acquiredAt: `${day}T05:30:00.000Z`, resolutionM: 10, cloudCover: kind === 'optical' ? 12 : null, orbitDirection: kind === 'sar' ? 'descending' : null, relativeOrbit: kind === 'sar' ? 1 : null, crs: 'EPSG:4326', footprintBbox: bbox, license: 'Synthetic demonstration data. Not real imagery.', attribution: 'VYRA demonstration generator', original: { synthetic: true, note: 'Generated by VYRA for demonstration. Does not depict the real world.', day }, synthetic: true, access: { day } }
}

export function demoProvider(enabled: () => boolean): ImageryProvider {
  return {
    id: 'demo',
    status(): ProviderStatus {
      return { id: 'demo', name: 'DEMONSTRATION (synthetic data)', description: 'Generates fake scenes to demonstrate the workflow. Never shows the real world.', state: enabled() ? 'ready' : 'disabled', missing: enabled() ? [] : ['SATELLITE_DEMO_MODE'], message: enabled() ? 'Demonstration mode is ON. Results are synthetic and cannot be confirmed.' : 'Demonstration mode is off. Set SATELLITE_DEMO_MODE=true to enable it.', collections: ['sentinel-2-l2a', 'sentinel-1'], license: 'Synthetic', attribution: 'VYRA demonstration generator', demo: true }
    },
    async search(req: SearchRequest): Promise<SearchResult> {
      if (!enabled()) throw new ProviderError('unsupported', 'Demonstration mode is off.', 400)
      if (req.collection !== 'sentinel-2-l2a' && req.collection !== 'sentinel-1') throw new ProviderError('unsupported', 'Demonstration data covers Sentinel-2 style and Sentinel-1 style scenes only.', 400)
      return { scenes: [sceneFor(req.collection, mid(req.start, req.end), req.bbox)], skipped: 0, notes: ['DEMONSTRATION: this scene is synthetic.'] }
    },
    async getScene(collection, id) {
      const m = /^demo-[a-z0-9-]+-(\d{4})(\d{2})(\d{2})$/.exec(id)
      if (!enabled() || !m) throw new ProviderError('not_found', 'No such demonstration scene.', 404)
      return sceneFor(collection, `${m[1]}-${m[2]}-${m[3]}`, null)
    },
    async load(scene: SceneMeta, grid: Grid): Promise<LoadedScene> {
      const n = grid.width * grid.height
      const isAfter = scene.access?.role === 'after' // the service marks which side of the comparison this scene is
      const rand = rng(Math.round((grid.bbox[0] + grid.bbox[1]) * 1e4) ^ (isAfter ? 77 : 11))
      const flags = new Uint8Array(n)
      const centre = (u: number) => 0.5 + 0.12 * Math.sin(2 * Math.PI * u * 1.5)
      const halfWidth = (u: number) => 0.025 + (isAfter ? 0.075 * Math.exp(-(((u - 0.5) / 0.25) ** 2)) : 0)
      const sar = scene.kind === 'sar'
      const bands: LoadedScene['bands'] = sar ? { vv: new Float32Array(n), vh: new Float32Array(n) } : { blue: new Float32Array(n), green: new Float32Array(n), red: new Float32Array(n), nir: new Float32Array(n), swir: new Float32Array(n) }
      for (let r = 0; r < grid.height; r++)
        for (let c = 0; c < grid.width; c++) {
          const i = r * grid.width + c, u = (c + 0.5) / grid.width, v = (r + 0.5) / grid.height
          const water = Math.abs(v - centre(u)) < halfWidth(u)
          const cloud = isAfter && !sar && (u - 0.18) ** 2 + (v - 0.2) ** 2 < 0.1 ** 2
          const cleared = isAfter && u > 0.7 && u < 0.88 && v > 0.65 && v < 0.85
          if (sar) {
            const looks = (mean: number) => { let s = 0; for (let k = 0; k < 4; k++) s += -Math.log(1 - rand()); return (mean * s) / 4 }
            const db = water ? -24 : cleared ? -11 : -9
            bands.vv![i] = looks(Math.pow(10, db / 10)); bands.vh![i] = looks(Math.pow(10, (db - 6) / 10))
          } else {
            const nz = () => (rand() - 0.5) * 0.02
            if (cloud) { flags[i] |= FLAG.CLOUD; for (const k of ['blue', 'green', 'red', 'nir', 'swir'] as const) bands[k]![i] = 0.7 + nz() }
            else if (water) { bands.blue![i] = 0.07 + nz(); bands.green![i] = 0.08 + nz(); bands.red![i] = 0.05 + nz(); bands.nir![i] = 0.03 + nz(); bands.swir![i] = 0.02 + nz() }
            else { const crop = cleared ? 0.14 : 0.36; bands.blue![i] = 0.05 + nz(); bands.green![i] = 0.10 + nz(); bands.red![i] = 0.09 + nz(); bands.nir![i] = crop + nz() * 2; bands.swir![i] = 0.22 + nz() }
          }
        }
      return { bands, flags, maskAvailable: true }
    },
  }
}
