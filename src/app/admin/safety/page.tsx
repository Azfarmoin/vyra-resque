'use client'

// Administrators: edit, review-stamp, publish and retire Hazards & Precautions guides, with revision history.
// A guide can only go live if it passes the content checks AND carries a reviewer and a review date.
import { useCallback, useEffect, useMemo, useState } from 'react'
import SiteHeader from '@/components/common/SiteHeader'
import Scene from '@/components/safety/Scene'
import { useSession } from '@/lib/session'
import { authHeaders } from '@/lib/zones/client'
import { formatTime } from '@/lib/client'
import { GUIDES, SCENE_IDS, SCENES, getGuide, type HazardId } from '@/lib/safety'
import { lintGuide } from '@/lib/safety/lint'
import type { SafetyAction, SafetyRevision, SafetyRow } from '@/lib/safety/admin'

export default function AdminSafetyPage() {
  const { user, ready } = useSession()
  const isAdmin = user?.role === 'admin'
  const [rows, setRows] = useState<SafetyRow[]>([])
  const [hazard, setHazard] = useState<HazardId>('flood')
  const [text, setText] = useState('')
  const [by, setBy] = useState('')
  const [on, setOn] = useState('')
  const [reason, setReason] = useState('')
  const [revs, setRevs] = useState<SafetyRevision[]>([])
  const [msg, setMsg] = useState<{ ok: boolean; text: string } | null>(null)
  const [busy, setBusy] = useState(false)

  const call = useCallback(async (path: string, init: { method?: string; body?: unknown } = {}) => {
    const res = await fetch(path, { method: init.method || 'GET', cache: 'no-store', headers: { 'Content-Type': 'application/json', ...(await authHeaders(user)) }, body: init.body ? JSON.stringify(init.body) : undefined })
    const data = await res.json().catch(() => ({}))
    if (!res.ok) throw new Error(data.error || `Request failed (${res.status})`)
    return data
  }, [user])

  const load = useCallback(async () => {
    try { setRows((await call('/api/safety/content?all=1')).rows) } catch (e) { setMsg({ ok: false, text: (e as Error).message }) }
  }, [call])
  useEffect(() => { if (ready && isAdmin) load() }, [ready, isAdmin, load])

  const row = rows.find((r) => r.hazard_id === hazard)
  useEffect(() => {
    setText(JSON.stringify(row?.content ?? getGuide(hazard), null, 2)); setReason(''); setMsg(null)
    setBy(row?.reviewed_by ?? ''); setOn(row?.reviewed_on ?? '')
    if (isAdmin) call(`/api/safety/content/${hazard}/revisions`).then((d) => setRevs(d.revisions)).catch(() => setRevs([]))
  }, [hazard, row?.revision, isAdmin]) // eslint-disable-line react-hooks/exhaustive-deps

  const parsed = useMemo(() => { try { return { guide: JSON.parse(text), error: '' } } catch (e) { return { guide: null, error: (e as Error).message } } }, [text])
  const problems = useMemo(() => (parsed.guide ? lintGuide({ ...parsed.guide, id: hazard === parsed.guide.id ? parsed.guide.id : parsed.guide.id }) : [parsed.error]), [parsed, hazard])

  const act = async (action: SafetyAction) => {
    setBusy(true); setMsg(null)
    try {
      await call(`/api/safety/content/${hazard}`, { method: 'PUT', body: { action, content: action === 'retire' ? undefined : parsed.guide, reviewed_by: by, reviewed_on: on, change_reason: reason } })
      setMsg({ ok: true, text: action === 'publish' ? 'Published. People will see this guide after their next refresh.' : action === 'retire' ? 'Retired. The built-in guide is shown again.' : 'Draft saved. It is not visible to the public.' })
      await load()
    } catch (e) { setMsg({ ok: false, text: (e as Error).message }) } finally { setBusy(false) }
  }

  if (!ready) return <div className="page min-h-screen"><SiteHeader /></div>
  if (!isAdmin) return <div className="page min-h-screen"><SiteHeader /><main id="main" className="mx-auto max-w-xl p-6"><div className="clay p-6" style={{ borderRadius: 28 }}><h1 className="font-display text-2xl font-semibold">Safety content</h1><p className="mt-2">Only administrators can manage safety content.</p></div></main></div>

  return (
    <div className="page min-h-screen">
      <SiteHeader />
      <main id="main" className="mx-auto max-w-5xl space-y-4 p-3 sm:p-5">
        <h1 className="font-display text-3xl font-semibold">Safety content</h1>
        <p className="text-ink-700">Life-safety instructions. Publish only text that a qualified person has reviewed against trusted sources. Nothing generated by AI can be published here without that review.</p>

        <div className="clay space-y-3 p-4" style={{ borderRadius: 28 }}>
          <label className="label" htmlFor="sc-h">Category</label>
          <select id="sc-h" className="input" value={hazard} onChange={(e) => setHazard(e.target.value as HazardId)}>
            {GUIDES.map((g) => { const r = rows.find((x) => x.hazard_id === g.id); return <option key={g.id} value={g.id}>{g.title} ({r ? `${r.status}, revision ${r.revision}` : 'built-in'})</option> })}
          </select>
          <p className="text-sm">Currently shown to the public: <strong>{row?.status === 'published' ? `published revision ${row.revision}, reviewed by ${row.reviewed_by} on ${row.reviewed_on}` : 'the built-in guide (not yet expert-reviewed)'}</strong></p>

          <label className="label" htmlFor="sc-json">Guide content (JSON: steps, DO/DON&apos;T lists, waiting scenarios, sources, review dates)</label>
          <textarea id="sc-json" className="input font-mono text-xs" rows={18} spellCheck={false} value={text} onChange={(e) => setText(e.target.value)} />
          {problems.length > 0 ? (
            <ul className="space-y-1 rounded-xl bg-critical-100 p-3 text-sm font-semibold text-critical-700" role="alert">{problems.map((p) => <li key={p}>{p}</li>)}</ul>
          ) : <p className="rounded-xl bg-success-100 p-2.5 text-sm font-bold text-success-800" role="status">Content checks passed.</p>}

          <div className="grid gap-3 sm:grid-cols-2">
            <div><label className="label" htmlFor="sc-by">Reviewed by (person or organisation)</label><input id="sc-by" className="input" value={by} onChange={(e) => setBy(e.target.value)} /></div>
            <div><label className="label" htmlFor="sc-on">Review date</label><input id="sc-on" type="date" className="input" value={on} onChange={(e) => setOn(e.target.value)} /></div>
          </div>
          <div><label className="label" htmlFor="sc-why">Reason for this change</label><input id="sc-why" className="input" value={reason} onChange={(e) => setReason(e.target.value)} /></div>
          {msg && <p className={`rounded-xl p-2.5 text-sm font-bold ${msg.ok ? 'bg-success-100 text-success-800' : 'bg-critical-100 text-critical-700'}`} role={msg.ok ? 'status' : 'alert'}>{msg.text}</p>}
          <div className="flex flex-wrap gap-2">
            <button type="button" className="btn-ghost" disabled={busy || row?.status === 'published'} onClick={() => act('save_draft')}>Save draft</button>
            <button type="button" className="btn-primary" disabled={busy || problems.length > 0} onClick={() => act('publish')}>Publish as reviewed</button>
            <button type="button" className="btn-ghost" disabled={busy || row?.status !== 'published'} onClick={() => act('retire')}>Retire (show built-in guide)</button>
          </div>
        </div>

        <div className="clay p-4" style={{ borderRadius: 28 }}>
          <h2 className="font-display text-xl font-semibold">Revision history</h2>
          <ol className="mt-2 space-y-2 text-sm">
            {revs.map((r) => <li key={r.id} className="clay-inset p-2.5"><strong>Revision {r.revision}: {r.status}</strong> by {r.actor ?? 'unknown'} · {formatTime(r.created_at)}{r.reviewed_by && <> · reviewed by {r.reviewed_by} on {r.reviewed_on}</>}<br />Reason: {r.change_reason}</li>)}
            {!revs.length && <li className="text-ink-600">No saved revisions yet. The built-in guide has no history here.</li>}
          </ol>
        </div>

        <div className="clay p-4" style={{ borderRadius: 28 }}>
          <h2 className="font-display text-xl font-semibold">Illustrations you can use (set a step&apos;s &quot;scene&quot;)</h2>
          <p className="text-sm text-ink-700">Illustrations are part of the app. To add a new drawing, a developer adds it to the app; attaching arbitrary images to life-safety steps is intentionally not allowed.</p>
          <ul className="mt-3 grid grid-cols-2 gap-3 sm:grid-cols-4">{SCENE_IDS.map((id) => <li key={id} className="text-center text-xs"><Scene id={id} className="h-auto w-full" /><code>{id}</code><span className="sr-only">: {SCENES[id]}</span></li>)}</ul>
        </div>
      </main>
    </div>
  )
}
